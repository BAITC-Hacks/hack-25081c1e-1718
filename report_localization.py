def _localize_label(label):
    if label in _LABELS_KK:
        return _LABELS_KK[label]
    match = re.fullmatch(r"Пилоты\s+(\d+)", label)
    if match:
        return "Сынақтар " + match.group(1)
    match = re.fullmatch(r"План кампании\s+(\d+)", label)
    if match:
        return "Науқан жоспары " + match.group(1)
    return label


def localize_response(response, language="ru", translate_answer=True):
    """Return a deep-copied response with optional Kazakh answer/metadata."""
    language = _language(language)
    result = deepcopy(response) if isinstance(response, dict) else {}
    if language == "ru":
        return result
    if translate_answer and isinstance(result.get("answer"), str):
        result["answer"] = _translate_answer(result["answer"])
    citations = result.get("citations")
    if isinstance(citations, list):
        for citation in citations:
            if isinstance(citation, dict) and isinstance(citation.get("label"), str):
                citation["label"] = _localize_label(citation["label"])
    warnings = result.get("warnings")
    if isinstance(warnings, list):
        result["warnings"] = [_WARNING_KK.get(item, item) for item in warnings]
    return result
