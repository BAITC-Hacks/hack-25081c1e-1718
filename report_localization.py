def _language(language):
    value = str(language or "ru").lower()
    if value not in SUPPORTED_LANGUAGES:
        raise ValueError("language must be ru or kk")
    return value


def query_for_facts(message, language="ru"):
    """Return original text plus a Russian routing query for report scoping.

    ``message`` is intentionally retained byte-for-byte for the LLM.  The
    ``routing_message`` is only for existing Russian intent and campaign-number
    extraction code.
    """
    language = _language(language)
    original = message if isinstance(message, str) else ""
    routing = original
    if language == "kk":
        replacements = (
            (r"\b(\d{1,2})\s*-\s*(?:ші|ыншы|інші)?\s*науқан\b", r"\1 кампания"),
            (r"\bнауқ\w*\b", "кампания"),
            (r"\bкампания(?:лар|ны|ға|ның|да)?\b", "кампания"),
            (r"\b(?:және|мен|пен)\b", "и"),
            (r"\bбірінші\b", "первая"), (r"\bекінші\b", "вторая"),
            (r"\bүшінші\b", "третья"), (r"\bтөртінші\b", "четвертая"),
            (r"\bбесінші\b", "пятая"), (r"\bалтыншы\b", "шестая"),
            (r"\bжетінші\b", "седьмая"), (r"\bсегізінші\b", "восьмая"),
            (r"\bтоғызыншы\b", "девятая"), (r"\bоныншы\b", "десятая"),
            (r"\bгипотез(?:алар|аны|а)?\b", "гипотезы"),
            (r"\bзерттел(?:ді|ген|уі|у)\b", "исследовано"),
            (r"\bнұсқ(?:алар|аны|а)?\b", "варианты"),
            (r"\b(?:таңдалмады|таңдалмаған|таңдалмауы)\b", "не выбран"),
            (r"\bтаңдал(?:ды|ған|уы)\b", "выбрано"),
            (r"\bболжам(?:ы|ды|ға|ды)?\b", "прогноз"),
            (r"\bкүтілетін\b", "ожидаемый"), (r"\bресурс(?:тар|ты|қа|тың)?\b", "ресурсы"),
            (r"\bбюджет(?:і|ті|ке|тің)?\b", "бюджет"),
            (r"\bбайланыс(?:тар|ты|қа|тың)?\b", "коммуникации"),
            (r"\bарн(?:алар|аны|аға|асы)?\b", "каналы"),
            (r"\bқоңырау(?:лар|ды|ға)?\b", "звонки"),
            (r"\bпилот(?:тар|ты|қа|тың)?\b", "пилоты"),
            (r"\bсынақ\w*\b", "пилоты"),
            (r"\bтәуекел\w*\b", "риск"),
            (r"\bбелгісіздік(?:ті|ке|тің)?\b", "неопределённость"),
            (r"\bнәтиже(?:сі|ні|лер)?\b", "результат"),
            (r"\bжоспар(?:ы|ды|ға|дың)?\b", "план"),
            (r"\bжорамал\w*\b", "гипотезы"),
            (r"\bбайланысу\s+әрекет\w*\b", "контакты"),
        )
        for pattern, replacement in replacements:
            routing = re.sub(pattern, replacement, routing, flags=re.IGNORECASE)
    lowered = routing.lower()
    if re.search(r"гипотез|исслед|вариант|отброш|исключ|не выбран", lowered):
        intent = "research"
    elif re.search(r"прогноз|ожидаем|ошибка", lowered):
        intent = "forecast"
    elif re.search(r"ресурс|бюджет|контакт|лимит", lowered):
        intent = "resources"
    elif re.search(r"канал|push|sms|звон", lowered):
        intent = "channels"
    elif re.search(r"пилот|развед|наблюд", lowered):
        intent = "pilots"
    elif re.search(r"риск|неопредел|надёж", lowered):
        intent = "risk"
    elif re.search(r"результат|эффект|net|arpu", lowered):
        intent = "result"
    elif re.search(r"кампан|план|распредел", lowered):
        intent = "campaigns"
    else:
        intent = "unknown"
    return {"language": language, "original_message": original,
            "message": original, "routing_message": routing, "intent": intent}


